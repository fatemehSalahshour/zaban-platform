<?php

namespace App\Support;

/**
 * تمیز کردن رشته‌ی معنی فارسی یک کلمه.
 *
 * چرا لازم شد: ایمپورت معنی‌ها را **ادغام** می‌کند نه بازنویسی (عمدی است —
 * یک کلمه در کلوز یک معنی دارد و در پسیج معنی دیگر). ولی یکتاسازی‌اش فقط
 * روی تکه‌های جداشده با «/» و با مقایسه‌ی دقیقِ رشته‌ها بود. پس این دو تکه
 * برایش دو چیز متفاوت بودند:
 *
 *     «عینی»        و      «عینی، بی‌طرفانه»
 *
 * و با هر بار ایمپورت، معنی‌ها روی هم تلنبار می‌شدند:
 *     عینی / بی‌طرفانه / عینی، بی‌طرفانه / هدف؛ عینی / بی‌طرف / هدف
 *
 * اینجا رشته به «واحدهای معنی» شکسته می‌شود — با «/»، «؛» و «،» — و هر واحد
 * فقط یک بار می‌ماند. مقایسه روی شکل نرمال‌شده است تا «ی/ك» عربی، نیم‌فاصله،
 * فاصله‌ی اضافه و اعراب، دو تا حسابش نکنند.
 */
final class Meanings
{
    /** سقف واحدها — بیشتر از این روی کارت مرور خوانده نمی‌شود و فقط شلوغ می‌کند */
    private const MAX = 12;

    public static function normalize(?string $fa): string
    {
        $fa = trim((string) $fa);
        if ($fa === '') return '';

        $atoms = preg_split('~[/؛;،,]+~u', $fa) ?: [];

        $out = [];
        $seen = [];
        foreach ($atoms as $atom) {
            /* «(تکرار)» نشانه‌ی کارِ ایمپورت است، نه بخشی از معنی */
            $atom = preg_replace('~\(\s*تکرار\s*\)~u', '', (string) $atom);
            $atom = trim(preg_replace('~\s+~u', ' ', $atom), " \t\n\r\0\x0B-–—");
            if ($atom === '') continue;

            $key = self::key($atom);
            if ($key === '' || isset($seen[$key])) continue;

            $seen[$key] = true;
            $out[] = $atom;
            if (count($out) >= self::MAX) break;
        }

        return implode(' / ', $out);
    }

    /** شکل مقایسه‌ای: بدون فاصله، نیم‌فاصله، اعراب و با حروف یکدست */
    private static function key(string $s): string
    {
        $s = strtr($s, [
            'ي' => 'ی', 'ك' => 'ک', 'ۀ' => 'ه', 'ة' => 'ه',
            'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ؤ' => 'و',
            "\u{200c}" => '', "\u{200f}" => '', "\u{200e}" => '',
        ]);
        $s = preg_replace('~[\s\x{064B}-\x{0652}\x{0640}]+~u', '', $s);
        return (string) $s;
    }
}
