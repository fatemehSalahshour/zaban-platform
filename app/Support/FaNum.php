<?php

namespace App\Support;

/**
 * عدد لاتین با جداکننده‌ی هزارگان ← رقم فارسی با جداکننده‌ی فارسی (٬).
 *
 * قبلاً این تبدیل فقط داخل routes/web.php (صفحه‌ی لندینگ) به‌صورت یک
 * closure محلی نوشته شده بود. همان‌جا ماند دست‌نخورده، ولی برای این‌که
 * صفحه‌ی خرید هم با همان قاعده‌ی «همه‌جای پلتفرم رقم فارسی» جلو برود،
 * همان منطق اینجا هم در دسترس است — یک‌بار تعریف، همه‌جا استفاده.
 */
class FaNum
{
    public static function format(int $n): string
    {
        return strtr(number_format($n), [
            '0' => '۰', '1' => '۱', '2' => '۲', '3' => '۳', '4' => '۴',
            '5' => '۵', '6' => '۶', '7' => '۷', '8' => '۸', '9' => '۹',
            ',' => '٬',
        ]);
    }
}
